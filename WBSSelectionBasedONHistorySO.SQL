SELECT DISTINCT 
    a.PS_PSP_PNR AS WBS_InternalID,
    prps.POSID AS WBSElement,
    prps.POST1 AS WBSText
FROM VBAK AS b
INNER JOIN VBAP AS a 
    ON b.MANDT = a.MANDT 
   AND b.VBELN = a.VBELN
INNER JOIN PRPS AS prps
    ON a.MANDT = prps.MANDT
   AND a.PS_PSP_PNR = prps.PSPNR
WHERE b.MANDT = '100'
  AND b.KUNNR IN (
    SELECT PARTNER
    FROM BUT000
    WHERE CLIENT = '100'
      AND NAME_ORG1 LIKE 'KUBOTA ENGINE%SHANGHAI%'
  )
  AND a.PS_PSP_PNR IS NOT NULL
  AND a.PS_PSP_PNR <> 0
ORDER BY prps.POSID;
