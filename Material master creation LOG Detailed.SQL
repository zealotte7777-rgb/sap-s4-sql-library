SELECT 
CDPOS.OBJECTCLAS,
CDPOS.OBJECTID,
CDPOS.CHANGENR,
CDPOS.TABNAME,
RIGHT( CDPOS.TABKEY, 4 ),
CDPOS.CHNGIND,
CDHDR.UDATE
FROM CDPOS
JOIN CDHDR
ON  CDHDR.MANDANT = CDPOS.MANDANT
AND CDHDR.CHANGENR = CDPOS.CHANGENR
WHERE CDPOS.OBJECTCLAS ='MATERIAL'
AND CDPOS.CHNGIND = 'I'
AND CDPOS.TABNAME = 'MARC'
AND CDHDR.USERNAME = YOUR_USER_NAME
AND CDHDR.MANDANT  = YOUR_CLIENT
ORDER BY CDHDR.UDATE,CDHDR.OBJECTID
