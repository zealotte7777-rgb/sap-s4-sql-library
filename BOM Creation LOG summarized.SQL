SELECT 
    SUB.UDATE,
    SUB.WERKS,
    COUNT( * ) AS BOM_COUNT
  FROM (
    SELECT DISTINCT
        SUBSTRING( CDPOS.OBJECTID, 5 ) AS BOMID,
        CDHDR.UDATE,
        MAST.WERKS
      FROM CDPOS
      JOIN CDHDR
        ON  CDHDR.MANDANT    = CDPOS.MANDANT
       AND  CDHDR.OBJECTCLAS = CDPOS.OBJECTCLAS
       AND  CDHDR.CHANGENR   = CDPOS.CHANGENR
      JOIN MAST
        ON  MAST.MANDT       = CDPOS.MANDANT
       AND  MAST.STLNR       = SUBSTRING( CDPOS.OBJECTID, 5 )
      WHERE CDPOS.OBJECTCLAS = 'STUE'
        AND CDPOS.CHNGIND    = 'I'
        AND CDPOS.MANDANT    = YOUR_CLIENT
        AND CDHDR.USERNAME   = YOUR_USER
  ) AS SUB
  GROUP BY SUB.UDATE, SUB.WERKS
  ORDER BY SUB.UDATE ASC, SUB.WERKS ASC;
