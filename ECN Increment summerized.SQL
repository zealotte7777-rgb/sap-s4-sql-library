SELECT 
    SUB.UDATE,
    SUB.LAST_CHAR,
    COUNT( * ) AS RECORD_COUNT
  FROM (
    SELECT DISTINCT
        CDHDR.UDATE,
        RIGHT( CDPOS.OBJECTID, 1 ) AS LAST_CHAR,
        CDPOS.OBJECTID
      FROM CDPOS
      JOIN CDHDR
        ON  CDHDR.MANDANT    = CDPOS.MANDANT
       AND  CDHDR.CHANGENR   = CDPOS.CHANGENR
      WHERE CDPOS.OBJECTCLAS = 'AENNR_S4H'
        AND CDPOS.TABNAME    = 'AENR'
        AND CDPOS.CHNGIND    = 'I'
        AND CDPOS.MANDANT    = YOUR_CLIENT
        AND CDHDR.USERNAME   = YOUR_USERNAME
  ) AS SUB
  GROUP BY SUB.UDATE, SUB.LAST_CHAR
  HAVING SUB.LAST_CHAR IN ( 'A', 'B', 'C', 'D', 'E' )
  ORDER BY SUB.UDATE ASC, SUB.LAST_CHAR ASC;
